	// Allow all fertilizers, and require them to have the same type.
    public static Supplier<TraceabilityPredicate> MIXING_MODULES = () -> new TraceabilityPredicate(blockWorldState -> {
        IBlockState blockState = blockWorldState.getBlockState();
        if (NepTechAPI.MIXING_MODULES.containsKey(blockState)) {
        	IMixingModuleStats stats = NepTechAPI.MIXING_MODULES.get(blockState);
            Object currentCoil = blockWorldState.getMatchContext().getOrPut("MixingModule", stats);
            if (!currentCoil.equals(stats)) {
                blockWorldState.setError(new PatternStringError("neptech.multiblock.pattern.error.mixing_module"));
                return false;
            }
            blockWorldState.getMatchContext().getOrPut("VABlock", new LinkedList<>()).add(blockWorldState.getPos());
            return true;
        }
        return false;
    }, () -> NepTechAPI.MIXING_MODULES.entrySet().stream()
            // sort to make autogenerated jei previews not pick random coils each game load
            .sorted(Comparator.comparingInt(entry -> entry.getValue().getTier()))
            .map(entry -> new BlockInfo(entry.getKey(), null))
            .toArray(BlockInfo[]::new))
                    .addTooltips("neptech.multiblock.pattern.error.mixing_module");
    
    public static TraceabilityPredicate mixingModules() {
        return MIXING_MODULES.get();
    }
    
