	@Override
    protected void formStructure(PatternMatchContext context) {
        super.formStructure(context);
        
        Object mixerModule = context.get("MixingModule");
        if (mixerModule instanceof IMixingModuleStats) {
            this.processingSpeed = ((IMixingModuleStats) mixerModule).getProcessingSpeed();
            this.moduleTier = ((IMixingModuleStats) mixerModule).getTier();
        } else {
            this.processingSpeed = 0;
            this.moduleTier = GTValues.ULV;
        }
	}
	
	@Override
    public void checkStructurePattern() {
        if (!this.isStructureFormed()) {
            reinitializeStructurePattern();
        }
        super.checkStructurePattern();
        if(!getAbilities(MultiblockAbility.INPUT_LASER).isEmpty())
        {
        	if(moduleTier < GTValues.UV)
        	{
        		invalidateStructure();
        	}
        }
        if(getAbilities(MultiblockAbility.INPUT_ENERGY).isEmpty() && getAbilities(MultiblockAbility.INPUT_LASER).isEmpty())
        {
        	invalidateStructure();
        }
    }
	
