    @Override
    public TraceabilityPredicate autoAbilities(boolean checkEnergyIn,
                                               boolean checkMaintenance,
                                               boolean checkItemIn,
                                               boolean checkItemOut,
                                               boolean checkFluidIn,
                                               boolean checkFluidOut,
                                               boolean checkMuffler) {
        TraceabilityPredicate predicate = super.autoAbilities(checkMaintenance, checkMuffler);

        if (checkEnergyIn) {
            predicate = predicate.or(abilities(MultiblockAbility.INPUT_ENERGY).setMaxGlobalLimited(3).setPreviewCount(1))
            					 .or(abilities(MultiblockAbility.INPUT_LASER).setMaxGlobalLimited(1));
        }

        if (checkItemIn) {
            if (recipeMap.getMaxInputs() > 0) {
                predicate = predicate.or(abilities(MultiblockAbility.IMPORT_ITEMS).setPreviewCount(1));
            }
        }
        if (checkItemOut) {
            if (recipeMap.getMaxOutputs() > 0) {
                predicate = predicate.or(abilities(MultiblockAbility.EXPORT_ITEMS).setPreviewCount(1));
            }
        }
        if (checkFluidIn) {
            if (recipeMap.getMaxFluidInputs() > 0) {
                predicate = predicate.or(abilities(MultiblockAbility.IMPORT_FLUIDS).setPreviewCount(1));
            }
        }
        if (checkFluidOut) {
            if (recipeMap.getMaxFluidOutputs() > 0) {
                predicate = predicate.or(abilities(MultiblockAbility.EXPORT_FLUIDS).setPreviewCount(1));
            }
        }
        return predicate;
    }
    
    private float getProcessingSpeed()
    {
    	float f = (lDist - 2.0F) * -1;
    	f += processingSpeed;
    	return f;
    }
	
	private boolean areAllEqual(int check, int... others)
	{
		for(int value : others)
		{
			if (value != check)
			{
				return false;
			}
		}
		return true;
	}
	
	private class MixingVesselLogic extends MultiblockRecipeLogic
	{
		private MetaTileEntityMixingVessel mte;
		public MixingVesselLogic(MetaTileEntityMixingVessel tileEntity) 
		{
			super(tileEntity);
			this.mte = tileEntity;
		}
		
		@Override
		public int getParallelLimit()
		{
			return (int) Math.pow(4, mte.lDist - 1);
		}
		
		@Override
        protected void modifyOverclockPost(int[] resultOverclock, @NotNull IRecipePropertyStorage storage) {
            super.modifyOverclockPost(resultOverclock, storage);

            if(mte.getProcessingSpeed() > 0)
            {
            	resultOverclock[1] /= mte.getProcessingSpeed(); 
                resultOverclock[1] = Math.max(1, resultOverclock[1]);
            }
            if(mte.getProcessingSpeed() < 0)
            {
            	float f = Math.abs(mte.getProcessingSpeed()); // Convert back into positive value
            	resultOverclock[1] *= f; 
            }
        }
	}

